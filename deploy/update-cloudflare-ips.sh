#!/usr/bin/env bash
# Regenerates deploy/caddy/cloudflare-ips.caddy from Cloudflare's published ranges.
# Run it on your laptop, commit the result, push, then deploy (see docs/deploy.md).
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
out="$here/caddy/cloudflare-ips.caddy"
tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT

v4="$(curl -fsS --max-time 20 https://www.cloudflare.com/ips-v4)"
v6="$(curl -fsS --max-time 20 https://www.cloudflare.com/ips-v6)"
ranges=""; count=0
while read -r cidr; do
  [ -n "$cidr" ] || continue
  if [[ "$cidr" =~ ^[0-9]{1,3}(\.[0-9]{1,3}){3}/[0-9]{1,2}$ ]] || [[ "$cidr" =~ ^[0-9a-fA-F:]+/[0-9]{1,3}$ ]]; then
    ranges="$ranges $cidr"; count=$((count + 1))
  else
    echo "update-cloudflare-ips: unexpected line in the downloaded list: $cidr" >&2; exit 1
  fi
done < <(printf '%s\n%s\n' "$v4" "$v6")
[ "$count" -ge 5 ] || { echo "update-cloudflare-ips: only $count ranges returned; refusing to write" >&2; exit 1; }
ranges="${ranges# }"

{
  echo "# Generated by deploy/update-cloudflare-ips.sh on $(date -u +%F) from"
  echo "# https://www.cloudflare.com/ips-v4 and /ips-v6. Do not edit by hand."
  echo "(cloudflare_guard) {"
  echo "	@notcloudflare {"
  echo "		expression \`'{\$CLOUDFLARE_ONLY:false}' == 'true'\`"
  echo "		not remote_ip $ranges"
  echo "	}"
  echo "	respond @notcloudflare \"Forbidden\" 403"
  echo "}"
} > "$tmp"
mv "$tmp" "$out"
trap - EXIT
echo "update-cloudflare-ips: wrote $out"
